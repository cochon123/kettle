// Offline shell for the circle app. Live data always comes over the WebSocket.
const CACHE = "kettle-circle-v1";
const SHELL = ["./", "index.html", "circle.css", "circle.js", "manifest.webmanifest", "../shared/kettle.css", "../shared/kettle.js", "../shared/logo.svg"];
self.addEventListener("install", (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting())));
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.pathname.startsWith("/api/")) return;
  e.respondWith(fetch(e.request).then((r) => { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); return r; })
    .catch(() => caches.match(e.request)));
});
