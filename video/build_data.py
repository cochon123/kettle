"""Collect the real numbers the film shows into video/data.js (every number on screen comes from data/)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "data"
OUT = Path(__file__).resolve().parent / "data.js"

base = json.loads((D / "refit/margaret_baseline.json").read_text())
days = []
for d in base["days"]:
    if not d["events"]:
        continue
    ev = [{"min": e["min"] + (1440 if e["min"] < 240 else 0), "label": e["label"], "w": e["dp_w"]} for e in d["events"]]
    days.append({"date": d["date"], "weekday": d["weekday"], "first": d["first_time"], "events": ev})

boil = json.loads((D / "refit/kettle_boil_trace.json").read_text())
jan = json.loads((D / "jan13_2024.json").read_text())
hourly = [h for h in jan["hourly"] if h["hour_start"].startswith("2024-01-13")]
weather = [w for w in jan["weather"] if w["t"].startswith("2024-01-13")]
summary = json.loads((D / "refit/summary.json").read_text())

data = {
    "house": base["house"],
    "days": days,
    "boil": {"step_w": boil["step_w"], "duration_s": boil["boil_duration_s"], "trace": boil["kettle_iam"]},
    "jan13": {
        "hourly": [{"h": int(h["hour_start"][11:13]), "price": h["pool_price"], "ail": h["ail_mw"]} for h in hourly],
        "weather": [{"h": int(w["t"][11:13]), "c": w["temp_c"]} for w in weather],
        "facts": jan["facts"],
        "timeline": jan["timeline"],
    },
    "refit": {
        "houses": summary["houses"],
        "home_days": summary["home_days"],
        "f1_plug": summary["kettle_f1_plug"],
        "checkins": summary["checkins_per_home_month"]["v0_kettle_plug"]["standard"],
        "checkins_paused": summary["checkins_per_home_month_away_paused"]["v0_kettle_plug"]["standard"],
    },
}
OUT.write_text("// Generated by build_data.py from ../data. Do not edit.\nwindow.KDATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
print("wrote", OUT, OUT.stat().st_size, "bytes;", len(days), "days")
